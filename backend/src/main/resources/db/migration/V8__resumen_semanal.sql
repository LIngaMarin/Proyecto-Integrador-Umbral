CREATE TABLE resumenes_semanales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL,
    semana_inicio DATE NOT NULL,
    destinatario VARCHAR(254) NOT NULL,
    asunto VARCHAR(255) NOT NULL,
    cuerpo TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0,
    ultimo_error VARCHAR(255),
    creado TIMESTAMP NOT NULL,
    enviado TIMESTAMP,
    CONSTRAINT uq_resumen_docente_semana UNIQUE(docente_id,semana_inicio)
);
CREATE INDEX idx_resumenes_pendientes ON resumenes_semanales(estado,intentos);
