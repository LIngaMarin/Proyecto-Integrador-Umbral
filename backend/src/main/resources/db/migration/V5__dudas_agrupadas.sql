CREATE TABLE grupos_dudas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(64) NOT NULL UNIQUE,
    docente_id BIGINT NOT NULL,
    seccion_id BIGINT NOT NULL,
    tema VARCHAR(255) NOT NULL,
    pregunta_id BIGINT REFERENCES preguntas(id)
);
CREATE INDEX idx_grupos_docente ON grupos_dudas(docente_id, seccion_id);
CREATE TABLE dudas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id BIGINT NOT NULL REFERENCES grupos_dudas(id),
    alumno_id BIGINT NOT NULL,
    texto VARCHAR(4000) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','RESUELTA')),
    fecha TIMESTAMP NOT NULL
);
CREATE INDEX idx_dudas_alumno_estado ON dudas(alumno_id,estado);
CREATE INDEX idx_dudas_grupo ON dudas(grupo_id);
