-- Registra puntaje y temas incorrectos por alumno, simulacro y sección.
CREATE TABLE resultados_simulacro (
    -- Identificador autogenerado que actúa como clave primaria.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Identificadores obligatorios guardados como valores numéricos.
    simulacro_id BIGINT NOT NULL,
    alumno_id BIGINT NOT NULL,
    seccion_id BIGINT NOT NULL,
    puntaje DOUBLE PRECISION NOT NULL,
    -- Temas incorrectos en formato JSON almacenado como texto.
    temas_incorrectos_json TEXT NOT NULL
);

-- Índice utilizado para recuperar registros por sección.
CREATE INDEX idx_resultados_simulacro_seccion_id
    ON resultados_simulacro (seccion_id);
