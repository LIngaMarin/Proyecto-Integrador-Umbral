-- Tablas propias del portal; no modifica el esquema administrativo compartido.
CREATE TABLE clases_web (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL,
    seccion_id BIGINT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    fin TIMESTAMP NOT NULL,
    cerrada BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_clases_web_cierre ON clases_web(cerrada,fin);
CREATE TABLE asistencias_web (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id BIGINT NOT NULL REFERENCES clases_web(id),
    alumno_id BIGINT NOT NULL,
    UNIQUE(clase_id,alumno_id)
);
CREATE TABLE notificaciones_academicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id BIGINT NOT NULL REFERENCES clases_web(id),
    alumno_id BIGINT NOT NULL,
    apoderado_id BIGINT NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    UNIQUE(clase_id,alumno_id,apoderado_id)
);
