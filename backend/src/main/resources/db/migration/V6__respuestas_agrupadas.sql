CREATE TABLE respuestas_grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id BIGINT NOT NULL REFERENCES grupos_dudas(id),
    docente_id BIGINT NOT NULL,
    texto VARCHAR(10000) NOT NULL,
    fecha TIMESTAMP NOT NULL
);
ALTER TABLE dudas ADD COLUMN respuesta_id BIGINT REFERENCES respuestas_grupo(id);
CREATE INDEX idx_dudas_respuesta ON dudas(respuesta_id);
