-- Guarda un solucionario por pregunta, con pasos, explicación opcional y estado.
CREATE TABLE solucionarios (
    -- Identificador autogenerado que actúa como clave primaria.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Referencia obligatoria y única a preguntas(id): limita a uno por pregunta.
    pregunta_id BIGINT NOT NULL UNIQUE REFERENCES preguntas (id),
    -- Desarrollo obligatorio y explicación de errores opcional.
    paso_a_paso TEXT NOT NULL,
    explicacion_errores_comunes TEXT,
    -- Estado textual del solucionario.
    estado VARCHAR(32) NOT NULL
);
