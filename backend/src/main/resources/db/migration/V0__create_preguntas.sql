-- Esquema base requerido por V1 y por el banco de preguntas existente.
CREATE TABLE preguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado TEXT,
    tema VARCHAR(255),
    dificultad VARCHAR(255),
    respuesta_correcta VARCHAR(255),
    estado VARCHAR(255),
    motivo_rechazo VARCHAR(255),
    docente_id BIGINT NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL
);

CREATE TABLE pregunta_opciones (
    pregunta_id BIGINT NOT NULL REFERENCES preguntas (id),
    opciones VARCHAR(255)
);

CREATE INDEX idx_preguntas_practica ON preguntas (estado, tema, dificultad);
